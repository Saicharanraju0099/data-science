-- COMPARISION OPERATOR --
-- EQUAL TO --
/* RETRIEVE ALL CUSTOMERS FROM GERMANY */
USE MyDatabase;
SELECT * 
FROM customers
where country = 'Germany'

-- NOT EQUAL TO --
/* RETRIEVE ALL CUSTOMERS WHO ARE NOT FROM GERMANY */

SELECT * 
FROM customers
where country != 'Germany';
-- GREATER THAN > --
/* RETRIEVE ALL CUSTOMERS WITH A SCORE GREATER THAN 500 */
SELECT *
FROM customers
WHERE score > 500

-- GREATER THAN AND EQUAL TO >= --
/* RETRIEVE ALL CUSTOMERS WITH A SCORE OF 500 OR MORE*/
SELECT *
FROM customers
WHERE score >= 500

-- LESS THAN AND EQUAL TO <= --
/* RETRIEVE ALL CUSTOMERS WITH A SCORE LESS THAN 500*/
SELECT *
FROM customers
WHERE score <= 500

-- LESS THAN AND EQUAL TO >= --
/* RETRIEVE ALL CUSTOMERS WITH A SCORE OF 500 OR LESS*/
SELECT *
FROM customers
WHERE score <= 500

-- LESS THAN AND EQUAL TO <= --
/* RETRIEVE ALL CUSTOMERS WITH A SCORE LESS THAN 500*/
SELECT *
FROM customers
WHERE score <= 500

-- LESS THAN AND EQUAL TO >= --
/* RETRIEVE ALL CUSTOMERS WITH A SCORE OF 500 OR LESS*/
SELECT *
FROM customers
WHERE score <= 500

-- LOGICAL OPERATORS --
-- AND --
/* RETRIEVE ALL CUSTOMERS WHO ARE FROM THE USA 
AND HAVE A SCORE GRETER THEN 500*/

SELECT * 
FROM customers
WHERE country = 'USA' AND score > 500

-- OR OPERATOR --
/* RETRIEVE ALL CUSTOMERS WHO ARE EITHER FROM THE USA
OR HAVE A SCORE GREATER THAN 500 */
SELECT *
FROM 
customers
WHERE country = 'USA' AND score > 500

/* RETRIEVE ALL CUSTOMERS WITH A SCORE NOT LESS THAN 500 */
SELECT *
FROM 
customers
WHERE NOT score > 500

-- RANGE OPERATOR --
/* RETRIEVE ALL CUSTOMERS WHOSE A SCORE FALLS IN THE
RANGE BETWEEN 100 AND 500 */
SELECT * 
FROM customers
WHERE score BETWEEN 100 AND 500
-- ANOTHER METHOD --
SELECT * 
FROM customers
WHERE score >= 100 AND score <= 500

-- MEMBERSHIP OPERATOR --
-- IN --
/* RETRIEVE ALL CUSTOMERS FROM EITHER GERMANY OR USA */
SELECT * 
FROM customers
WHERE country = 'Germany' OR country = 'USA'

-- ANOTHER METHOD --
SELECT * 
FROM customers
WHERE COUNTRY IN ('Germany','USA')

-- NOT IN --
/* RETRIEVE ALL CUSTOMERS NOT FROM  GERMANY OR USA */
SELECT * 
FROM customers
WHERE COUNTRY NOT IN ('Germany','USA')

-- LIKE OPERATOR --
/* FIND ALL CUSTOMERS WHOSE FIRST NAME STARTS WITH 'M' */
SELECT *
FROM customers
WHERE first_name LIKE '%M'

/* FIND ALL CUSTOMERS WHOSE FIRST NAME ENDS WITH 'n' */
SELECT *
FROM customers
WHERE first_name LIKE '%n'

/* FIND ALL CUSTOMERS WHOSE FIRST NAME CONTAINS 'r' */
SELECT * 
FROM customers
WHERE first_name LIKE '%n%'

/* FIND ALL CUSTOMERS WHOSE FIRST NAME HAS 'r' IN THE THIRD POSITION */
SELECT * 
FROM customers
WHERE first_name LIKE '__r%'






