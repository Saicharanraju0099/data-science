USE MyDatabase

-- SQL JOINS --
/* RETRIEVE ALL DATA FROM CUSTOMERS AND ORDERS AS SEPARATE RESULTS */

SELECT * 
FROM customers;

SELECT * 
FROM orders;

-- INNER JOIN --
/* GET ALL CUSTOMERS ALONG WITH THIER ORDERS, BUT ONLY FOR CUSTOMERS WHO
HAVE PLACED AN ORDER */
SELECT 
    C.id,
    C.first_name,
    O.order_id,
    O.sales
FROM customers AS C
INNER JOIN orders AS O
ON C.id = O.customer_id