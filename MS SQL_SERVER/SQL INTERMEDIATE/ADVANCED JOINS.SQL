-- LEFT ANTI JOIN --
/* GET ALL CUSTOMERS WHO HAVEN'T PLACED ANY ORDER */
SELECT * 
FROM customers AS C
LEFT JOIN orders AS O
ON C.id = O.customer_id
WHERE O.customer_id IS NULL

-- RIGHT ANTI JOIN --
/* GET ALL ORDERS WITHOUT MATCHING CUSTOMERS */
SELECT * 
FROM customers AS C
RIGHT JOIN orders AS O
ON C.id = O.customer_id
WHERE C.id IS NULL

