-- LEFT ANTI JOIN --
/* GET ALL CUSTOMERS WHO HAVEN'T PLACED ANY ORDER */
SELECT * 
FROM customers AS C
LEFT JOIN orders AS O
ON C.id = O.customer_id
WHERE O.customer_id IS NULL

-- RIGHT ANTI JOIN --
/* GET ALL ORDERS WITHOUT MATCHING CUSTOMERS */
SELECT * 
FROM customers AS C
RIGHT JOIN orders AS O
ON C.id = O.customer_id
WHERE C.id IS NULL

-- TASK (USING LEFT JOIN) --
/* GET ALL ORDERS WITHOUT MATCHING THE CUSTOMERS */
SELECT * 
FROM orders AS O
LEFT JOIN customers AS C
ON C.id = O.customer_id
WHERE  c.id IS NULL

-- FULL ANTI JOIN --
/* FIND CUSTOMERS WITHOUT ORDERS AND ORDERS WITHOUT CUSTOMERS */
SELECT * 
FROM orders AS O
FULL JOIN customers AS C
ON C.id = O.customer_id
WHERE C.id IS NULL OR customer_id IS NULL

-- TASK (WITHOUT USING INNER JOIN) --
/* GET ALL CUSTOMERS ALONG WITH THEIR ORDERS, BUT ONLY FOR 
CUSTOMERS WHO HAVE PLACED AN ORDER */
SELECT *
FROM customers AS C
LEFT JOIN orders AS O
ON C.id = O.customer_id
WHERE O.customer_id IS NOT NULL

-- CROSS JOIN --
SELECT *
FROM customers
CROSS JOIN orders

-- TASK USING MULTI JOIN --
/* USING SALES DB, RETRIEVE A LIST OF ALL ORDERS, ALONG WITH THE RELATED 
CUSTOMER, PRODUCT, AND EMPLOYEE DETAILS 
FOR EACH ORDER, DISPLAY:
ORDER ID, CUSTOMER NAME, PRODUCT NAME, SALES AMOUNT, PRODUCT PRICE, SALES PERSON'S NAME
*/
SELECT 
    O.OrderID,
    O.Sales,
    C.FirstName AS CustomerFirstName,
    c.LastName AS CustomerLastName,
    P.Product AS ProductName,
    P.Price,
    E.FirstName AS EmployeeFirstName,
    E.LastName AS EmployeeLastName
FROM Sales.Orders AS O
LEFT JOIN Sales.Customers AS C
ON O.CustomerID = C.CustomerID
LEFT JOIN Sales.Products AS P
ON O.ProductID = P.ProductID
LEFT JOIN Sales.Employees AS E
ON O.SalesPersonID = E.EmployeeID



